package org.example.task3;

import java.util.List;
import java.util.Map;

/**
 * ДАННЫЕ ЗАДАЧИ РЕШАТЬ ТОЛЬКО ИСПОЛЬЗУЯ STREAM API.
 * ДРУГОЙ ВАРИАНТ, ХОТЬ И ПРАВИЛЬНЫЙ, ПРИНЯТ НЕ БУДЕТ
 * НАДО УМЕТЬ РАБОТАТЬ С STREAM API.
 * ИЗУЧИТЕ ЕЩЕ Collectors - там полезные методы есть
 */
public interface Task3_1 {

    /**
     * Есть метод, который принимает список целых чисел.
     * Необходимо:
     * 1. Оставить только чётные числа.
     * 2. Каждое умножить на 10.
     * 3. Вернуть результат в виде нового списка.
     * Например: [1, 2, 3, 4, 5, 6] -> [20, 40, 60]
     *
     * @param numbers список целых чисел
     * @return новый список чётных чисел, умноженных на 10
     */
    List<Integer> filterAndMultiply(List<Integer> numbers);

    /**
     * Есть метод, который принимает список целых чисел.
     * Необходимо с помощью Stream API посчитать:
     * 1. Сумму всех элементов.
     * 2. Среднее арифметическое.
     * 3. Максимальный элемент.
     * 4. Минимальный элемент.
     * Вернуть результат в виде Map с ключами "sum", "average", "max", "min".
     *
     * @param numbers список целых чисел
     * @return Map с результатами: sum, average, max, min
     */
    Map<String, Double> calculateStats(List<Integer> numbers);

    /**
     * Есть метод, который принимает список строк.
     * Необходимо сгруппировать строки по их длине.
     * Например: ["a", "bb", "cc", "ddd", "ee"]
     *        -> {1: ["a"], 2: ["bb", "cc", "ee"], 3: ["ddd"]}
     * Использовать Stream API: Collectors.groupingBy.
     *
     * @param words список строк
     * @return Map, где ключ — длина строки, значение — список строк этой длины
     */
    Map<Integer, List<String>> groupByLength(List<String> words);

    /**
     * Есть метод, который принимает список строк и число n.
     * Необходимо:
     * 1. Отсортировать строки по длине (от большей к меньшей).
     * 2. При равной длине — по алфавиту.
     * 3. Вернуть первые n строк.
     * Например: ["apple", "cat", "banana", "dog", "kiwi"], n = 3
     *        -> ["banana", "apple", "kiwi"]
     *
     * @param words список строк
     * @param n     количество строк для возврата (n > 0)
     * @return список из первых n строк после сортировки
     */
    List<String> topNLongest(List<String> words, int n);

    /**
     * Есть метод, который принимает список списков целых чисел.
     * Необходимо:
     * 1. "Развернуть" вложенные списки в один плоский список.
     * 2. Оставить только уникальные значения.
     * 3. Отсортировать по возрастанию.
     * 4. Вернуть результат.
     * Например: [[3, 1, 2], [2, 4], [5, 1]] -> [1, 2, 3, 4, 5]
     *
     * <p>прочитайте про flatMap - очень часто используется, нужно понимать как работает</>
     *
     * @param nestedLists список списков целых чисел
     * @return плоский отсортированный список уникальных чисел
     */
    List<Integer> flattenAndSort(List<List<Integer>> nestedLists);

    /**
     * Есть метод, который принимает список целых чисел.
     * Необходимо с помощью Stream API:
     * 1. Разделить числа на чётные и нечётные (partitioningBy).
     * 2. Для каждой группы посчитать:
     *    - количество элементов,
     *    - сумму элементов,
     *    - среднее значение.
     * 3. Вернуть результат в виде Map, где ключи:
     *    "even_count", "even_sum", "even_avg",
     *    "odd_count", "odd_sum", "odd_avg".
     * Например: [1, 2, 3, 4, 5, 6]
     *        -> even_count = 3, even_sum = 12, even_avg = 4.0
     *           odd_count = 3,  odd_sum = 9,  odd_avg = 3.0
     *
     * @param numbers список целых чисел (не пустой)
     * @return Map со статистикой по чётным и нечётным числам
     */
    Map<String, Double> analyzeEvenOdd(List<Integer> numbers);

    /**
     * Есть метод, который принимает список имён.
     * Необходимо вернуть новый список, где каждое имя:
     * 1. Приведено к верхнему регистру.
     * 2. Обрезаны пробелы по краям.
     * 3. Пустые строки и null пропущены.
     * Например: [" аня ", "", null, "боря"] -> ["АНЯ", "БОРЯ"]
     *
     * @param names список имён (может содержать null и пустые строки)
     * @return новый список обработанных имён в верхнем регистре
     */
    List<String> normalizeNamesStream(List<String> names);
}
