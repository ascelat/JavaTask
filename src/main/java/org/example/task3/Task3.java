package org.example.task3;

import java.util.List;
import java.util.Map;
import java.util.Set;

public interface Task3 {

    /**
     * Есть метод, который принимает список целых чисел.
     * Необходимо удалить из него все дубликаты, сохранив порядок
     * первого появления каждого элемента.
     * Например: [1, 2, 2, 3, 1, 4, 3] -> [1, 2, 3, 4]
     *
     * @param numbers исходный список целых чисел (может содержать дубликаты)
     * @return новый список без дубликатов с сохранением порядка
     */
    List<Integer> removeDuplicates(List<Integer> numbers);


    /**
     * Есть метод, который принимает два списка целых чисел.
     * Необходимо вернуть множество элементов, которые встречаются
     * одновременно в обоих списках (пересечение).
     * Например: [1, 2, 3, 4] и [3, 4, 5, 6] -> {3, 4}
     *
     * @param first  первый список целых чисел
     * @param second второй список целых чисел
     * @return множество общих элементов (без дубликатов)
     */
    Set<Integer> findIntersection(List<Integer> first, List<Integer> second);

    /**
     * Есть метод, который принимает список строк.
     * Необходимо посчитать, сколько раз встречается каждая строка,
     * и вернуть результат в виде Map, где ключ — строка,
     * значение — количество её вхождений.
     * Например: ["java", "python", "java", "c++", "java"]
     *        -> {"java": 3, "python": 1, "c++": 1}
     *
     * @param words список строк (может содержать дубликаты и null-значения игнорируются)
     * @return Map, где ключ — уникальная строка, значение — частота
     */
    Map<String, Integer> countWords(List<String> words);

    /**
     * Есть метод, который принимает Map, где ключ — имя студента,
     * значение — его оценка (от 1 до 5).
     * Необходимо "перевернуть" структуру: сгруппировать имена студентов
     * по их оценкам.
     * Например: {"Аня": 5, "Боря": 4, "Вера": 5, "Гена": 3, "Дима": 4}
     *        -> {5: ["Аня", "Вера"], 4: ["Боря", "Дима"], 3: ["Гена"]}
     *
     * @param students Map с именами студентов и их оценками
     * @return Map, где ключ — оценка, значение — список имён студентов с этой оценкой
     */
    Map<Integer, List<String>> groupByGrade(Map<String, Integer> students);

    /**
     * Есть метод, который принимает список целых чисел.
     * Необходимо найти элемент, который встречается чаще всего.
     * Если таких элементов несколько (одинаковая максимальная частота),
     * вернуть наименьший из них.
     * Например: [3, 1, 3, 2, 1, 3] -> 3 (встречается 3 раза)
     *           [5, 5, 2, 2, 3]   -> 2 (2 и 5 встречаются по 2 раза, берём минимальный)
     *
     * @param numbers список целых чисел (не пустой)
     * @return наиболее часто встречающийся элемент
     */
    int findMostFrequent(List<Integer> numbers);

    /**
     * Есть метод, который принимает два множества строк.
     * Необходимо:
     * 1. Найти их объединение (все уникальные элементы из обоих множеств).
     * 2. Найти их пересечение (элементы, присутствующие в обоих).
     * 3. Найти разность первого и второго (элементы только первого).
     * 4. Проверить, является ли первое множество подмножеством второго.
     * Вернуть результат в виде Map с ключами "union", "intersection",
     * "difference", "isSubset".
     *
     * @param first  первое множество строк
     * @param second второе множество строк
     * @return Map с результатами операций: union, intersection, difference, isSubset
     */
    Map<String, Object> compareSets(Set<String> first, Set<String> second);

    /**
     * Есть метод, который принимает список строк.
     * Необходимо посчитать суммарную длину всех строк в списке.
     * Например: ["java", "is", "cool"] -> 4 + 2 + 4 = 10
     *
     * <p>Реализовать через обычный цикл for-each.</p>
     *
     * @param words список строк (может содержать null)
     * @return суммарная длина всех непустых строк
     */
    int sumOfLengths(List<String> words);

    /**
     * Есть метод, который принимает список имён.
     * Необходимо вернуть новый список, где каждое имя:
     * 1. Приведено к верхнему регистру.
     * 2. Обрезаны пробелы по краям.
     * 3. Пустые строки и null пропущены.
     * Например: [" аня ", "", null, "боря"] -> ["АНЯ", "БОРЯ"]
     *
     * <p>Реализовать через обычный цикл for-each с накоплением
     * результата в новый список.</p>
     *
     * @param names список имён (может содержать null и пустые строки)
     * @return новый список обработанных имён в верхнем регистре
     */
    List<String> normalizeNames(List<String> names);
}
